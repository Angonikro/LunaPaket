#!/bin/bash
set -euo pipefail
ROOT="$(cd "$(dirname "$0")" && pwd)"
PKG="$ROOT/build/lunapaket-pkgroot"
OUT="$ROOT/dist"
VERSION="0.1.32"
rm -rf "$ROOT/build" "$OUT"
mkdir -p "$PKG/DEBIAN" "$PKG/usr/share/lunapaket" "$PKG/usr/share/doc/lunapaket" "$PKG/usr/bin" "$PKG/usr/share/applications" "$PKG/usr/share/mime/packages" "$OUT"
chmod 0755 "$PKG/DEBIAN"; chmod g-s "$PKG/DEBIAN"
install -m 0644 "$ROOT/debian/control" "$PKG/DEBIAN/control"
install -m 0644 "$ROOT/lunapaket/main.py" "$PKG/usr/share/lunapaket/main.py"
install -m 0644 "$ROOT/README.md" "$PKG/usr/share/doc/lunapaket/README.md"
install -m 0755 "$ROOT/lunapaket/lunapaket" "$PKG/usr/bin/lunapaket"
install -m 0644 "$ROOT/debian/lunapaket.desktop" "$PKG/usr/share/applications/lunapaket.desktop"
install -m 0644 "$ROOT/debian/lunapaket-deb.xml" "$PKG/usr/share/mime/packages/lunapaket-deb.xml"
install -m 0755 "$ROOT/debian/postinst" "$PKG/DEBIAN/postinst"
install -m 0755 "$ROOT/debian/postrm" "$PKG/DEBIAN/postrm"
dpkg-deb --root-owner-group --build "$PKG" "$OUT/lunapaket_${VERSION}_all.deb"
echo "Paket erstellt: $OUT/lunapaket_${VERSION}_all.deb"
